/*==========================================================
06 - COUNTDOWN TIMER (مؤقت انتهاء العرض)
============================================================

الوظيفة:
عرض عد تنازلي لإظهار أن العرض لفترة محدودة.

كيف يعمل؟

1- يبدأ من الوقت المحدد.
2- ينقص ثانية واحدة كل ثانية.
3- عندما تنتهي الثواني:
      ينتقل إلى الدقيقة السابقة.
4- عندما تنتهي الدقائق:
      ينتقل إلى الساعة السابقة.
5- عند انتهاء الوقت بالكامل:
      يعيد تشغيل المؤقت من جديد.

============================================================

يمكنك التعديل على:

✔ عدد الساعات.
✔ عدد الدقائق.
✔ عدد الثواني.

مثال:

12 ساعة
30 دقيقة
00 ثانية

============================================================

لا تعدل:

id="timer"

لأن JavaScript يعتمد عليه داخل index.html.

==========================================================*/


//==================================================
// وقت بداية العرض
//==================================================

let hours = OFFER_HOURS;   // من إعدادات المشروع
let minutes = 0;
let seconds = 0;


//==================================================
// عنصر المؤقت داخل الصفحة
//==================================================

const timer = document.getElementById("timer");


//==================================================
// تحديث المؤقت كل ثانية
//==================================================

function updateTimer() {

    // إذا لم يوجد عنصر المؤقت
    if (!timer) return;


    // انتهاء الثواني

    if (seconds === 0) {

        // انتهاء الدقائق

        if (minutes === 0) {

            // انتهاء الساعات

            if (hours === 0) {

                // إعادة تشغيل المؤقت

                hours = OFFER_HOURS;
                minutes = 0;
                seconds = 0;

            } else {

                // إنقاص ساعة

                hours--;
                minutes = 59;
                seconds = 59;

            }

        } else {

            // إنقاص دقيقة

            minutes--;
            seconds = 59;

        }

    } else {

        // إنقاص ثانية

        seconds--;

    }


    //==================================================
    // عرض الوقت داخل الصفحة
    //==================================================

    timer.innerHTML =

        String(hours).padStart(2, "0") + ":" +
        String(minutes).padStart(2, "0") + ":" +
        String(seconds).padStart(2, "0");

}


//==================================================
// تشغيل المؤقت كل ثانية
//==================================================

setInterval(updateTimer, 1000);
